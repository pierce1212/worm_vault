const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const core = require('../tasks-core.js');
const { build } = require('../tasks-today.js');
const plugin = fs.readFileSync(path.resolve(__dirname, '../../.obsidian/plugins/dataview/main.js'), 'utf8');
const source = plugin.slice(plugin.indexOf('// these'), plugin.indexOf('////////////////////', plugin.indexOf('var Luxon =')));
const { DateTime } = vm.runInNewContext(source + ';Luxon;', { Intl, Date });
const today = DateTime.fromISO('2026-10-12');
let line = 0;
const task = (text, status = ' ', children = []) => ({ text, status, completed: status === 'x', task: true, children, line: line++, path: '工作任务.md' });
const highest = task('最高 ⏳ 2026-10-12 🔺');
const due = task('今天截止 📅 2026-10-12 🔼');
const doing = task('无日期进行中', '/');
const started = task('今天开始 🛫 2026-10-12');
const child = task('子任务今天计划 ⏳ 2026-10-12 ⏫');
const parent = task('长期父任务', ' ', [child, task('未来最高子任务 🔺 📅 2026-12-31')]);
const overdue = task('逾期待安排 📅 2026-10-01');
const scheduledLate = task('逾期但今日已计划 📅 2026-10-01 ⏳ 2026-10-12');
const future = task('未来待办 ⏳ 2026-10-13 📅 2026-12-31');
const noDate = task('无日期待办');
const postponed = task('延期父任务 ⏳ 2026-10-12', '>', [task('进行子任务', '/')]);
const blocked = task('阻塞 [tcc_blocked:: true] ⏳ 2026-10-12', '/');
const cancelled = task('取消 📅 2026-10-12', '-');
const done = task('完成 ✅ 2026-10-12', 'x');
const oldDone = task('昨天完成 ✅ 2026-10-11', 'x');
const nestedWait = task('延期分支不参与', ' ', [task('延期分支', '>', [task('日期今天 📅 2026-10-12')])]);
const roots = [noDate, future, due, parent, overdue, scheduledLate, started, highest, doing, postponed, blocked, cancelled, done, oldDone, nestedWait];
const all = roots.flatMap(root => [root, ...core.children(root)]);
const result = build(all, { core, DateTime, today });
assert.deepEqual(result.planned.slice(0, 3).map(entry => entry.task), [highest, parent, due]);
assert.equal(result.planned[1].childPriority, true);
assert.equal(result.planned[1].priority.label, '高', 'future children must not inflate today priority');
assert.deepEqual(new Set(result.planned.map(entry => entry.task)), new Set([highest, parent, due, doing, started, scheduledLate]));
assert.deepEqual(result.overdue.map(entry => entry.task), [overdue]);
assert.deepEqual(result.done.map(entry => entry.task), [done]);
assert(!result.planned.some(entry => entry.task === child), 'child is never rendered as a separate root');
const tomorrow = build(all, { core, DateTime, today: today.plus({ days: 1 }) });
assert(tomorrow.planned.some(entry => entry.task === future));
assert(!tomorrow.planned.some(entry => entry.task === highest));
assert(tomorrow.overdue.some(entry => entry.task === due));
console.log('PASS: today/date/status eligibility, priority ordering, child ownership, deferred overdue, completed tasks, paused branches and day rollover.');
