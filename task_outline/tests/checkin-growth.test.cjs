const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const { growth } = require('../task-checkins.js');
const source = fs.readFileSync(path.resolve(__dirname, '../../.obsidian/plugins/dataview/main.js'), 'utf8');
const { DateTime } = vm.runInNewContext(source.slice(source.indexOf('// these'), source.indexOf('////////////////////', source.indexOf('var Luxon ='))) + ';Luxon;', { Date, Intl });
const now = DateTime.fromISO('2026-10-30');
const entry = (day, taskId = 'A', kind = 'done', minutes = 20) => ({ day, taskId, kind, minutes });
const rows = [entry('2026-10-30'), entry('2026-10-30'), entry('2026-10-30', 'B'), entry('2026-10-29', 'A', 'rest', 0), entry('2026-10-25'), entry('2026-10-31')];
const summary = growth(rows, now);
assert.equal(summary.count, 3);
assert.equal(summary.xp, 30);
assert.equal(summary.level, 1);
assert.equal(summary.levelProgress, 30);
assert.equal(summary.activeDays, 2);
assert.equal(summary.weekCount, 2);
assert.equal(summary.minutes, 60);
assert.deepEqual(summary.milestones.filter(item => item.unlocked).map(item => item.count), [1, 3]);
assert.equal(summary.calendar.length, 28);
assert.equal(summary.calendar[0].day, '2026-10-05');
assert.equal(summary.calendar.find(item => item.day === '2026-10-30').count, 2);
assert.equal(summary.calendar.find(item => item.day === '2026-10-31').future, true);
assert.equal(summary.calendar.find(item => item.day === '2026-10-29').rest, true);
assert.equal(growth(rows.map(item => ({ ...item, minutes: 60, notePaths: ['a', 'b'] })), now).xp, 30, 'time and multiple notes do not farm XP');
const ten = Array.from({ length: 10 }, (_, i) => entry(now.minus({ days: i }).toFormat('yyyy-LL-dd')));
assert.equal(growth(ten, now).level, 2);
assert.equal(growth(ten, now).levelProgress, 0);
assert.equal(growth([...ten, entry('2026-10-20', 'A', 'rest', 0)], now).xp, 100, 'rest never deducts existing growth');
assert.equal(growth([], now).level, 1);
console.log('PASS: unique task/day XP, editing immunity, rest days, levels, milestones, weekly boundaries and calendar.');
